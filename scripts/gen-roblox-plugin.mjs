// Generates src/roblox/plugin-source.ts from roblox/LuMinal.server.luau, so the Studio plugin's
// source is compiled into lu-minal (the Bun single-file binaries have no files next to them).
// The .luau file is the one to edit; run this script afterwards. A test checks that both match.
//
//   node scripts/gen-roblox-plugin.mjs           write src/roblox/plugin-source.ts
//   node scripts/gen-roblox-plugin.mjs --check   exit 1 if it is out of date
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const luauFile = path.join(root, "roblox", "LuMinal.server.luau");
const tsFile = path.join(root, "src", "roblox", "plugin-source.ts");

/** The TypeScript module for a plugin source (line endings normalized to LF). */
export function renderPluginModule(source) {
  const text = source.replace(/\r\n/g, "\n");
  const match = /^local PLUGIN_VERSION = "([^"]+)"/m.exec(text);
  if (!match) throw new Error('roblox/LuMinal.server.luau has no `local PLUGIN_VERSION = "x.y.z"` line.');
  const lines = text.split("\n").map((line) => `  ${JSON.stringify(line)},`);
  return [
    "// GENERATED by scripts/gen-roblox-plugin.mjs from roblox/LuMinal.server.luau - do not edit by hand.",
    "// The Roblox Studio plugin's source, compiled into lu-minal so `lu-minal roblox install` works from",
    "// the single-file binaries too. Edit the .luau file, then run `node scripts/gen-roblox-plugin.mjs`.",
    "",
    "/** The plugin's version (its `PLUGIN_VERSION`); the bridge compares it with what Studio reports. */",
    `export const PLUGIN_VERSION = ${JSON.stringify(match[1])};`,
    "",
    "/** The plugin's full Luau source (LF line endings), with the default port 44766. */",
    "export const PLUGIN_SOURCE: string = [",
    ...lines,
    '].join("\\n");',
    "",
  ].join("\n");
}

function main() {
  const check = process.argv.includes("--check");
  const wanted = renderPluginModule(fs.readFileSync(luauFile, "utf8"));
  const current = fs.existsSync(tsFile) ? fs.readFileSync(tsFile, "utf8").replace(/\r\n/g, "\n") : "";
  if (check) {
    if (current !== wanted) {
      console.error("src/roblox/plugin-source.ts is out of date: run `node scripts/gen-roblox-plugin.mjs`.");
      process.exit(1);
    }
    console.log("src/roblox/plugin-source.ts is up to date.");
    return;
  }
  if (current === wanted) {
    console.log("src/roblox/plugin-source.ts is already up to date.");
    return;
  }
  fs.writeFileSync(tsFile, wanted);
  console.log(`Wrote ${path.relative(root, tsFile)}.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
